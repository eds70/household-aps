 $md$# Как построить план

**Категория:** Планирование

Страница **«Планирование»** — основной инструмент создания плана.

## Параметры расчёта

| Поле | По умолчанию | Что означает |
|------|--------------|--------------|
| Горизонт (часы) | 720 (30 дней) | На сколько вперёд строить план |
| Таймаут solver (сек) | 600 | Максимальное время работы solver |

Параметры сохраняются в `app_settings` при построении плана.

## Что происходит при нажатии «Построить план»

1. Параметры сохраняются в `app_settings`.
2. Запускается OR-Tools CP-SAT solver.
3. Solver строит расписание с учётом техкарт, цепочек, ресурсов,
 календаря, режима смен.
4. Результат сохраняется как новая версия плана.
5. Обновляются Advisor и «История планов».

## Сколько ждать

- 7–25 секунд — для простых what-if.
- 30–120 секунд — для полного месячного плана.
- до 600 секунд — на пределе таймаута.

> ⚠️ Не закрывайте страницу во время расчёта.

## Статусы решения

| Статус | Что значит |
|--------|------------|
| OPTIMAL | Оптимальное решение |
| FEASIBLE | Решение не оптимальное |
| INFEASIBLE | Решение не найдено |
| UNKNOWN | Статус не определён |

