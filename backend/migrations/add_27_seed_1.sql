## Доступные туры

### 1. Первый план за 5 минут

Базовый тур для новых пользователей. Покажет:

- где находятся основные разделы;
- как проверить справочники;
- как построить первый план;
- как открыть диаграмму Ганта.

**Время прохождения:** ~5 минут.

### 2. Основы работы с диаграммой Ганта

Тур по диаграмме Ганта. Покажет:

- как читать диаграмму;
- как переключать режимы (просмотр / редактирование);
- как перетаскивать задачи;
- как закрепить задачу.

**Время прохождения:** ~3 минуты.

### 3. Работа мастера смены

Тур по рабочему месту мастера. Покажет:

- как выбрать смену;
- как вносить факт выполнения;
- как заблокировать / разблокировать партию.

**Время прохождения:** ~2 минуты.

## Как запустить тур

1. Откройте раздел **Помощь**.
2. В левой панели выберите статью **«Интерактивные туры»**.
3. Нажмите кнопку **«Начать»** рядом с нужным туром.

Тур можно **пропустить** на любом шаге (кнопка «Пропустить»).
Если тур был пройден, при следующем запуске появится
предупреждение — можно пройти заново, нажав **«Пройти заново»**.

