$md$# Advisor: подсказки планировщика

**Категория:** Планирование

**Advisor** — встроенный аналитик. После построения или открытия
плана проверяет данные и показывает подсказки.

## Уровни важности

| Уровень | Цвет | Когда |
|---------|------|-------|
| 🔴 CRITICAL | Красный | План невыполним |
| 🟡 WARNING | Оранжевый | Есть риск |
| 🔵 INFO | Синий | Информация |

## Типы подсказок

### 🔴 MATERIAL_SHORTAGE — дефицит сырья

Потребность > остатки. Что делать: увеличить остатки или уменьшить
объём.

### 🟡 UNDERLOAD — неполная загрузка реактора

Партия загружает реактор < порога. Что делать: увеличить объём.

### 🔵 ROUTE_MISMATCH — маршрут не совпадает

Продукт VIA_TANK, но реактор не подключён к танку.

### 🔵 EQUIPMENT_GAP — простой оборудования

Большой разрыв между операциями.

### 🔵 COOLING_DEGRADATION — замедленное охлаждение

2+ реактора охлаждаются одновременно.

### 🟡 CZ_INCOMPLETE — партия не промаркирована

Задача слива DONE, но партия не достигла порога ЧЗ.

## Как читать

1. Начните с CRITICAL.
2. Раскройте подсказку кликом.
3. Пересчитайте план после устранения.

## Чего Advisor НЕ делает

- Не блокирует построение.
- Не учитывает график поставок в реальном времени.
- Не заменяет лабораторию и мастера.

