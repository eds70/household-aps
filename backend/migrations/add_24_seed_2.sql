- Тянется только тело задачи.
- Snap — 15 минут.
- Курсор `grab` → `grabbing`.

Tooltip при перетаскивании показывает:

- тип операции;
- новое время;
- исходное время;
- Δ в минутах;
- сколько задач сдвинется.

## Изменение длительности

- Тяните за левый / правый край.
- Минимум 5 мин, максимум 24 ч.

