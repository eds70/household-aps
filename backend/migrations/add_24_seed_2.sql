**Категория:** Планирование

**Пересчёт** — повторный запуск solver с учётом правок. Кнопка в
тулбаре Ганта.

## Когда кнопка активна

Только при `planDirty === true`. Что помечает план «грязным»:

- перетаскивание / resize задачи;
- pin / unpin;
- изменение справочников;
- изменение заказов / партий;
- capacity пулов;
- лабораторные блокировки;
- `calendar_event`;
- `app_settings` / `plan_settings`.

## Что происходит

1. Открывается модальное окно прогресса с таймером.
2. Запускается solver.
3. По завершении:
   - создаётся новая версия;
- старая — в архив (если `auto_archive_on_recalc`);
- снекбар: 🟢 архивирована / 🟡 не архивирована.
4. `planDirty` сбрасывается.

## Прогресс-диалог

Спиннер, таймер MM:SS, прогресс-бар, предупреждение «Не закрывайте
страницу».

## Если plan_settings пуст

Диалог **«Настройки плана не заполнены»**:

1. **Открыть мастер настроек** — заполнить вручную.
2. **Пересчитать без изменений** — использовать `app_settings`.

