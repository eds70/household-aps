**Категория:** Настройки

В системе два уровня настроек.

## app_settings

Глобальные настройки организации. Единый источник правды. Хранит
все параметры: планирование, режим смен, охлаждение, календарь,
 ЧЗ, оптимизация.

     Редактируются на странице **«Настройки»** (ADMIN / PLANNER).

## plan_settings

Снапшот настроек конкретного плана. Копируется из `app_settings`
при создании плана (через триггер `copy_app_settings_to_plan`).

**Зачем:** воспроизводимость. Изменение `app_settings` не ломает
старые планы.

## Приоритет чтения

1. Если задан `version_id` — сначала `plan_settings`.
2. Если там нет — `app_settings`.
3. Если и там нет — default.

## Когда что редактировать

| Ситуация | Что |
|----------|-----|
| Глобально для всех будущих | app_settings |
| Только один план | plan_settings (мастер) |
| Воспроизвести старый | не трогать |
| Сбросить план к глобальным | мастер → «Сбросить» |

## Мастер настроек

Открывается из «Истории планов» через **⚙**. 9 шагов.

Изменённые поля помечены чипом «изменено» (жёлтый).

## Сброс

Кнопка **«Сбросить к глобальным»** удаляет `plan_settings` и
копирует свежие `app_settings`.

> ⚠️ После сброса пересчитайте план.

## Старые планы

Планы до Итерации 13.14 могут не иметь `plan_settings`. Работают
через fallback на `app_settings`.

